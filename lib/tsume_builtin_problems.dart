// lib/tsume_builtin_problems.dart
// tsume_screen.dart に埋め込まれていた内蔵詰将棋問題データを純Dartファイルへ分離。
// tsume_screen.dart は flutter/material.dart 等に依存するため `dart run` では
// コンパイルできず、tool/validate_tsume_screen.dart から検証できなかった。
// このファイルは piece.dart / logic.dart のみに依存する純Dartのため検証可能。

import 'piece.dart';
import 'logic.dart';

class TsumeProb {
  final String title;
  final int moves;
  final List<List<Piece?>> board;
  final Map<PieceType, int> p1Hand;
  final Map<PieceType, int> p2Hand;
  final bool p1Turn;
  // 手順: 偶数インデックス(0,2,4)=先手の手、奇数インデックス(1,3)=後手の応手
  final List<AMove> solution;
  final String explanation;

  const TsumeProb({
    required this.title,
    required this.moves,
    required this.board,
    required this.p1Hand,
    required this.p2Hand,
    // ignore: unused_element_parameter
  this.p1Turn = true,
    required this.solution,
    this.explanation = '',
  });
}

List<List<Piece?>> _empty() =>
    List.generate(9, (_) => List<Piece?>.filled(9, null));

List<TsumeProb> buildTsumeProblems({bool skipStartPositionFilter = false}) {
  final list = <TsumeProb>[];

  // ===== 1手詰め ① =====
  // 後手玉 1一(0,0)、先手金 2三(2,1)→1二(1,0) 王手
  // 後手玉の逃げ場: 2一=銀あり×、1二=金打ちマス×、2二=飛(3,1)の縦効き×
  {
    final b = _empty();
    b[0][0] = Piece(PieceType.king, false);   // 後手玉 1一(0,0)
    b[8][8] = Piece(PieceType.king, true);    // 先手玉 9九(8,8)
    b[2][1] = Piece(PieceType.gold, true);    // 先手金 2三(2,1) ← 解答手
    b[0][1] = Piece(PieceType.silver, true);  // 先手銀 2一(0,1) ← 逃げ場封鎖
    b[3][1] = Piece(PieceType.rook, true);    // 先手飛 2四(3,1) ← 2二封鎖
    list.add(TsumeProb(
      title: '1手詰め ①',
      moves: 1,
      board: b,
      p1Hand: {},
      p2Hand: {},
      solution: [
        AMove(fr: 2, fc: 1, tr: 1, tc: 0), // 金 2三→1二(王手・詰み)
      ],
      explanation: '金を2三から1二に引いて後手玉に王手をかけます。銀と飛が逃げ道を塞いでいるため詰み。',
    ));
  }

  // ===== 1手詰め ② =====
  // 後手玉 9一(0,8)、先手銀 8一(0,7)、先手金 9三(2,8)
  // 手順: 金 8二(1,7)打ち → 詰み
  {
    final b = _empty();
    b[0][8] = Piece(PieceType.king,   false); // 後手玉 9一(0,8)
    b[8][4] = Piece(PieceType.king,   true);  // 先手玉 5九(8,4)
    b[0][7] = Piece(PieceType.silver, true);  // 先手銀 8一(0,7) ← 8一封鎖
    b[2][8] = Piece(PieceType.gold,   true);  // 先手金 9三(2,8) ← 9二封鎖・8二守備
    list.add(TsumeProb(
      title: '1手詰め ②',
      moves: 1,
      board: b,
      p1Hand: {PieceType.gold: 1},
      p2Hand: {},
      solution: [
        AMove(fr: -1, fc: -1, tr: 1, tc: 7, drop: PieceType.gold), // 金 8二打ち(王手・詰み)
      ],
      explanation: '持ち駒の金を8二に打ちます。8一は銀が封鎖し、9二は9三の金が守り、打った金自身も8二を守るため詰み。',
    ));
  }

  // ===== 1手詰め ③ =====
  // 先手龍で王手・詰め
  // (旧版は龍・金が共に開始局面から後手玉に王手をかけてしまう不正な局面だった。
  //  TsumeEngineでの検証により発覚・修正: 龍は斜め1マスで5二に踏み込み、
  //  桂馬が5二を紐付けする形に変更)
  // 後手玉 5一(0,4)、先手龍 4三(2,3)、先手桂 4四(3,3)
  // 手順: 龍 4三→5二(1,4)で王手（龍の八方効きで四方封鎖、桂が5二を守る）
  {
    final b = _empty();
    b[0][4] = Piece(PieceType.king, false);          // 後手玉 5一(0,4)
    b[8][4] = Piece(PieceType.king, true);            // 先手玉 5九(8,4)
    b[2][3] = Piece(PieceType.promotedRook, true);   // 先手龍 4三(2,3)
    b[3][3] = Piece(PieceType.knight, true);          // 先手桂 4四(3,3) ← 5二を守る
    list.add(TsumeProb(
      title: '1手詰め ③',
      moves: 1,
      board: b,
      p1Hand: {},
      p2Hand: {},
      solution: [
        AMove(fr: 2, fc: 3, tr: 1, tc: 4), // 龍 4三→5二(斜め、王手・詰み)
      ],
      explanation: '龍を4三から斜めに5二へ踏み込んで王手。龍が隣接する8マス全てを利き、桂馬が5二を守っているため取られず詰み。',
    ));
  }

  // ===== 1手詰め ④ =====
  // 後手玉 5一(0,4)、先手銀 4一(0,3)・6一(0,5)、先手龍 6三(2,5)
  // 手順: 龍 6三→5二(1,4)で王手・詰み
  {
    final b = _empty();
    b[0][4] = Piece(PieceType.king,         false); // 後手玉 5一(0,4)
    b[8][4] = Piece(PieceType.king,         true);  // 先手玉 5九(8,4)
    b[0][3] = Piece(PieceType.silver,       true);  // 先手銀 4一(0,3) ← 4一封鎖・5二守備
    b[0][5] = Piece(PieceType.silver,       true);  // 先手銀 6一(0,5) ← 6一封鎖
    b[2][5] = Piece(PieceType.promotedRook, true);  // 先手龍 6三(2,5)
    list.add(TsumeProb(
      title: '1手詰め ④',
      moves: 1,
      board: b,
      p1Hand: {},
      p2Hand: {},
      solution: [
        AMove(fr: 2, fc: 5, tr: 1, tc: 4), // 龍 6三→5二(王手・詰み)
      ],
      explanation: '龍を6三から5二に移動させて5一の後手玉に王手。4一・6一は銀が塞ぎ、4二・5二・6二は龍が封鎖するため詰み。',
    ));
  }

  // ===== 1手詰め ⑤ =====
  // 持ち駒の銀を打って詰める
  // (旧版は金・飛が共に開始局面から王手をかけてしまう不正な局面だった。
  //  TsumeEngineでの検証により発覚・修正)
  // 後手玉 9一(0,8)、先手金 7三(2,7) ← 8二・9二を守る、先手銀 8三(1,6) ← 8一を守る
  // (金・銀だけで開始局面から後手玉の全逃げ場を封鎖してしまい、王手はして
  //  いないものの合法手が無い＝終端状態になっていたため、後手に歩を持たせて
  //  開始局面に合法手を残した)
  // 手順: 銀 8二(1,7)打ち
  {
    final b = _empty();
    b[0][8] = Piece(PieceType.king, false);   // 後手玉 9一(0,8)
    b[8][8] = Piece(PieceType.king, true);    // 先手玉 9九(8,8)
    b[2][7] = Piece(PieceType.gold, true);    // 先手金 7三(2,7) ← 8二・9二を守る
    b[1][6] = Piece(PieceType.silver, true);  // 先手銀 8三(1,6) ← 8一を守る
    b[4][4] = Piece(PieceType.pawn, false);   // 後手歩（開始局面が終端状態になるのを防ぐ）
    list.add(TsumeProb(
      title: '1手詰め ⑤',
      moves: 1,
      board: b,
      p1Hand: {PieceType.silver: 1},
      p2Hand: {},
      solution: [
        AMove(fr: -1, fc: -1, tr: 1, tc: 7, drop: PieceType.silver), // 銀 8二打ち(王手・詰み)
      ],
      explanation: '持ち駒の銀を8二に打って王手をかけます。8一は銀が、9二は金が守っているため詰み。',
    ));
  }

  // ===== 1手詰め ⑥ =====
  // (旧版は馬・金2枚・銀の全てが開始局面から王手をかけてしまう不正な局面
  //  だった。TsumeEngineでの検証により発覚・修正)
  // 後手玉 5一(0,4)、先手馬 5三(2,4)、先手金 7二(1,2) ← 4一・4二を守る、
  // 先手桂 3四(3,6) ← 6二を守る
  // 手順: 馬 5三→6二(1,5)で王手（馬の八方効きで四方封鎖、桂が6二を守る）
  {
    final b = _empty();
    b[0][4] = Piece(PieceType.king, false);           // 後手玉 5一(0,4)
    b[8][4] = Piece(PieceType.king, true);             // 先手玉 5九(8,4)
    b[2][4] = Piece(PieceType.promotedBishop, true);   // 先手馬 5三(2,4)
    b[1][2] = Piece(PieceType.gold, true);             // 先手金 7二(1,2) ← 4一・4二を守る
    b[3][6] = Piece(PieceType.knight, true);           // 先手桂 3四(3,6) ← 6二を守る
    list.add(TsumeProb(
      title: '1手詰め ⑥',
      moves: 1,
      board: b,
      p1Hand: {},
      p2Hand: {},
      solution: [
        AMove(fr: 2, fc: 4, tr: 1, tc: 5), // 馬 5三→6二(斜め、王手・詰み)
      ],
      explanation: '馬を5三から斜めに6二へ踏み込んで王手。馬が隣接8マスを利き、桂馬が6二を守っているため取られず詰み。',
    ));
  }

  // ===== 1手詰め ⑦ =====
  // 持ち駒の金を打って端玉を詰める
  // (旧版は金・飛が共に開始局面から王手をかけてしまう不正な局面だった。
  //  TsumeEngineでの検証により発覚・修正: 桂馬1枚で打った金を守る形に変更)
  // 後手玉 1一(0,0)、先手桂 2四(3,1) ← 1二を守る
  // 手順: 金 1二(1,0)打ち（金自身が2一・2二を利き、桂が金を守るため詰み）
  {
    final b = _empty();
    b[0][0] = Piece(PieceType.king, false);   // 後手玉 1一(0,0)
    b[8][8] = Piece(PieceType.king, true);    // 先手玉 9九(8,8)
    b[3][1] = Piece(PieceType.knight, true);  // 先手桂 2四(3,1) ← 1二を守る
    list.add(TsumeProb(
      title: '1手詰め ⑦',
      moves: 1,
      board: b,
      p1Hand: {PieceType.gold: 1},
      p2Hand: {},
      solution: [
        AMove(fr: -1, fc: -1, tr: 1, tc: 0, drop: PieceType.gold), // 金 1二打ち(王手・詰み)
      ],
      explanation: '持ち駒の金を1二に打って王手をかけます。金自身が2一・2二を塞ぎ、桂馬が金を守っているため詰み。',
    ));
  }

  // ===== 3手詰め ① =====
  // 飛で後手歩を取り王手→後手玉4一に逃げ→金5二打ち詰め
  // (旧版は銀・金が共に開始局面から王手をかけてしまう不正な局面だった。
  //  TsumeEngineでの検証により発覚・修正: 銀・金を桂馬3枚に置き換えて
  //  各逃げ場を静かに守る形にした)
  // 後手玉 3一(0,2)、先手飛 3五(4,2)、後手歩 3三(2,2) ← 飛の王手を遮断、
  // 先手桂 9三(2,0) ← 2一を守る、先手桂 3三(3,2) ← 2二・4二を守る、
  // 先手桂 4三(3,3) ← 3二・5二を守る
  // 手順: 飛 3五→3三(後手歩取り、縦で王手)→後手玉4一(唯一の逃げ)→金5二打ち詰み
  {
    final b = _empty();
    b[0][2] = Piece(PieceType.king, false);   // 後手玉 3一(0,2)
    b[8][8] = Piece(PieceType.king, true);    // 先手玉 9九(8,8)
    b[4][2] = Piece(PieceType.rook, true);    // 先手飛 3五(4,2)
    b[2][2] = Piece(PieceType.pawn, false);   // 後手歩 3三(2,2) ← 飛の王手を遮断
    b[2][0] = Piece(PieceType.knight, true);  // 先手桂 9三(2,0) ← 2一を守る
    b[3][2] = Piece(PieceType.knight, true);  // 先手桂 3三(3,2) ← 2二・4二を守る
    b[3][3] = Piece(PieceType.knight, true);  // 先手桂 4三(3,3) ← 3二・5二を守る
    list.add(TsumeProb(
      title: '3手詰め ①',
      moves: 3,
      board: b,
      p1Hand: {PieceType.gold: 1},
      p2Hand: {},
      solution: [
        AMove(fr: 4, fc: 2, tr: 2, tc: 2),                           // 飛 3五→3三(後手歩取り、王手)
        AMove(fr: 0, fc: 2, tr: 0, tc: 3),                           // 後手玉 3一→4一(唯一の逃げ)
        AMove(fr: -1, fc: -1, tr: 1, tc: 4, drop: PieceType.gold),  // 金 5二打ち(詰み)
      ],
      explanation: '飛で後手歩を取りながら王手。桂馬3枚が周囲を守っているため後手玉は4一にしか逃げられません。最後に金を5二に打つと、飛の縦利きと桂馬の守りで全逃げ道が塞がり詰みます。',
    ));
  }

  // ===== 3手詰め ② =====
  // 龍で後手歩を取り王手→後手玉2一に逃げ→角(馬)成りで詰み
  // 後手玉 1一(0,0)、先手龍 1六(5,0)、先手金 3三(2,2)、先手角 2三(2,1)、後手歩 1四(3,0)
  // 手順:
  //   1. 龍 1六→1四(後手歩取り、縦で王手)
  //   2. 後手玉 1一→2一(0,1)逃げ(唯一の逃げ: 1二は龍縦・2二は金斜め封鎖)
  //   3. 角 2三→3二成(1,2)、王手。2一の逃げ道は
  //      1一=龍の縦利き、3一=馬の縦利き、2二=金と馬の利きで全て封鎖、
  //      馬自体も金が守っているため取れず、詰み。
  // (以前は3手目に龍を1一へ寄せる手を解として登録していたが、
  //  1一の龍は無防備で王が取れてしまい実際には詰んでいなかった。
  //  TsumeEngine.findMate による検証で不成立と判明したため、
  //  角を追加して正しく詰む形に修正した)
  {
    final b = _empty();
    b[0][0] = Piece(PieceType.king, false);          // 後手玉 1一(0,0)
    b[8][8] = Piece(PieceType.king, true);            // 先手玉 9九(8,8)
    b[5][0] = Piece(PieceType.promotedRook, true);   // 先手龍 1六(5,0)
    b[2][2] = Piece(PieceType.gold, true);            // 先手金 3三(2,2)
    b[2][1] = Piece(PieceType.bishop, true);          // 先手角 2三(2,1)
    b[3][0] = Piece(PieceType.pawn, false);           // 後手歩 1四(3,0) ← 龍の王手を遮断
    list.add(TsumeProb(
      title: '3手詰め ②',
      moves: 3,
      board: b,
      p1Hand: {},
      p2Hand: {},
      solution: [
        AMove(fr: 5, fc: 0, tr: 3, tc: 0),  // 龍 1六→1四(後手歩取り、縦で王手)
        AMove(fr: 0, fc: 0, tr: 0, tc: 1),  // 後手玉 1一→2一(0,1)逃げ
        AMove(fr: 2, fc: 1, tr: 1, tc: 2, promote: true),  // 角 2三→3二成(1,2)、詰み
      ],
      explanation: '龍で後手歩を取りながら王手。後手玉は2一に逃げるしかなく、角が3二に成って馬になると、金と龍の利きで全逃げ道が塞がれ詰みです。',
    ));
  }

  // ===== 3手詰め ③ =====
  // (旧版は香が開始局面から王手をかけている上、解答の最終手も後手玉のマス
  //  へ直接移動する不成立な手だった。TsumeEngineでの検証により発覚・修正:
  //  飛の遠見王手→唯一の逃げ→金打ちの3手に再設計)
  // 後手玉 9一(0,8)、先手飛 6二(1,3) ← 9二へ横に成らず王手、
  // 先手金 7三(2,7) ← 9二を守る、先手桂 4四(3,5) ← 8二を守る
  // 手順:
  //   1. 飛 6二→9二(1,8) 王手（列で王手、8二・9二は飛の利きで塞がる）
  //   2. 後手玉 9一→8一(0,7) 逃げ(唯一の逃げ)
  //   3. 金 8二(1,6)打ち 王手・詰み(金が8一・8二・9二を利き、桂が金を守る)
  {
    final b = _empty();
    b[0][8] = Piece(PieceType.king, false);   // 後手玉 9一(0,8)
    b[8][0] = Piece(PieceType.king, true);    // 先手玉 1九(8,0)
    b[1][3] = Piece(PieceType.rook, true);    // 先手飛 6二(1,3)
    b[2][7] = Piece(PieceType.gold, true);    // 先手金 7三(2,7) ← 9二を守る
    b[3][5] = Piece(PieceType.knight, true);  // 先手桂 4四(3,5) ← 8二を守る
    list.add(TsumeProb(
      title: '3手詰め ③',
      moves: 3,
      board: b,
      p1Hand: {PieceType.gold: 1},
      p2Hand: {},
      solution: [
        AMove(fr: 1, fc: 3, tr: 1, tc: 8),  // 飛 6二→9二(横に進めて王手)
        AMove(fr: 0, fc: 8, tr: 0, tc: 7),  // 後手玉 9一→8一(唯一の逃げ)
        AMove(fr: -1, fc: -1, tr: 1, tc: 6, drop: PieceType.gold), // 金 8二打ち(詰み)
      ],
      explanation: '飛を横に9二へ進めて王手。後手玉は8一にしか逃げられません。金を8二に打つと、金自身の利きと桂馬の守りで全逃げ道が塞がり詰みます。',
    ));
  }

  // ===== 3手詰め ④ =====
  // (旧版は金・銀が開始局面から後手玉に隣接し王手をかけている上、飛の1手目も
  //  斜め移動になっており不成立だった。TsumeEngineでの検証により発覚・修正:
  //  飛を王手ラインの外から進めて王手→唯一の逃げ→金打ちの3手に再設計)
  // 後手玉 5一(0,4)、先手飛 6二(1,1) ← 5二へ横に進め王手、
  // 桂 2三(2,2) ← 4一を守る、桂 6五(3,5) ← 5二(飛の着地点)を守る、桂 9三(2,7) ← 6一を守る
  // 手順:
  //   1. 飛 6二→5二(1,4) 王手（列で4一・5一・6一が飛の縦横利きで塞がる）
  //   2. 後手玉 5一→6一(0,5) 逃げ(唯一の逃げ)
  //   3. 金 7一(0,6)打ち 王手・詰み(金が6一・7一・8一を利き、桂が金を守る)
  {
    final b = _empty();
    b[0][4] = Piece(PieceType.king, false);   // 後手玉 5一(0,4)
    b[8][4] = Piece(PieceType.king, true);    // 先手玉 5九(8,4)
    b[1][1] = Piece(PieceType.rook, true);    // 先手飛 6二(1,1)
    b[2][2] = Piece(PieceType.knight, true);  // 先手桂 2三(2,2) ← 4一を守る
    b[3][5] = Piece(PieceType.knight, true);  // 先手桂 6五(3,5) ← 飛の着地点(1,4)を守る
