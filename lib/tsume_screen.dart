  //   飛を 1三(row2,col0) に → 縦に1二(1,0),1一(0,0)に効く
  //   後手玉 1一→1二: 飛(2,0)の効き(1,0)=1二✓ → 逃げられない ✓
  //   後手玉 1一→2一: 飛を(0,1)に置かないので誰かで塞ぐ
  //   先手銀 2一(row0,col1): 後手玉が2一に行けない(先手駒あり) ✓
