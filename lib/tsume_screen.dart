  Widget _handWidget(Map<PieceType, int> hand, {required bool isP1}) {
    if (hand.isEmpty) {
      return const Padding(
        padding: EdgeInsets.symmetric(vertical: 4),
        child: Text('なし', style: TextStyle(color: Colors.white38, fontSize: 12)),
      );
    }
    return Wrap(
      spacing: 8,
      runSpacing: 4,
      children: hand.entries.map((e) {
        final selected = isP1 && _selectedHandPiece == e.key;
        return GestureDetector(
          onTap: isP1 && _p1Turn && !_solved
              ? () {
                  setState(() {
                    _selectedHandPiece =
                        _selectedHandPiece == e.key ? null : e.key;
                    if (_selectedHandPiece != null) {
                      _selected = null;
                      _legalDots = {};
                    }
                  });
                }
              : null,
          child: Container(
            padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 6),
            decoration: BoxDecoration(
              color: selected
                  ? Colors.amber.shade700
                  : Colors.blueGrey.shade800,
              borderRadius: BorderRadius.circular(6),
              border: Border.all(
                color: selected
                    ? Colors.amber.shade300
                    : Colors.transparent,
                width: 1.5,
              ),
            ),
            child: Text(
              '${pieceLabel(e.key)}×${e.value}',
              style: const TextStyle(
                  color: Colors.white,
                  fontSize: 13,
                  fontWeight: FontWeight.bold),
            ),
          ),
        );
      }).toList(),
    );
  }

