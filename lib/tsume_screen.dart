      ],
      explanation: '金を1一に打って後手玉の逃げ道を封鎖します。飛が1二・2一を塞いでいるため詰み。',
    ));
  }

  // ===== 1手詰め ② =====
  // 持ち駒の金を打って詰める
  // 後手玉 9一(row0,col8)、先手飛 8三(row2,col7)、先手香 9三(row2,col8)
  // 手順: 金 8二(row1,col7)打ち
