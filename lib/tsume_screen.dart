    return Scaffold(
      backgroundColor: _bg,
      appBar: AppBar(
        backgroundColor: _card,
        title: const Text('詰将棋', style: TextStyle(color: Colors.white)),
        iconTheme: const IconThemeData(color: Colors.white),
