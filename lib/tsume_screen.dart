  // 後手玉 1一(row0,col0), 先手金 2二(row1,col1), 先手飛 2一(row0,col1)
  // 手順: 金 2二→1一 詰み
  //   後手玉の逃げ場: 2一=飛がいる, 2二=金がいる(動いた後は空き→飛の利き)
  //   金(1,1,fwd=-1): step(-1,-1)=(0,0)=1一✓, step(-1,0)=(0,1)=2一, step(-1,1)=(0,2)=3一
